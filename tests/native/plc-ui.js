async (page) => {
  if (!await page.evaluate(() => !!window.__uiOperations)) throw new Error("Run guard.js first");
  const read = (command, args) => page.evaluate(async ({ command, args }) => window.__TAURI_INTERNALS__.invoke(command, args), { command, args });
  const offline = await read("site_status");
  if (!(offline.mode === "offline")) throw new Error("PLC UI checks require the offline S7 line");
  await page.getByRole("navigation", { name: "操作导航" }).getByRole("link", { name: "PLC 通讯", exact: true }).click();
  const retention = page.getByRole("spinbutton", { name: "日志保留天数（0 为永久）", exact: true });
  const original = await retention.inputValue();
  await retention.fill(String(Number(original) === 7 ? 8 : 7));
  await page.getByRole("button", { name: "还原", exact: true }).click();
  if (await retention.inputValue() !== original) throw new Error("PLC restore did not recover the active configuration");
  await retention.fill(String(Number(original) === 7 ? 8 : 7));
  await page.getByRole("button", { name: "保存配置", exact: true }).click();
  await page.getByText(/退出离线后再修改/).first().waitFor();
  if ((await read("plc_get_config")).logRetentionDays !== Number(original)) throw new Error("Offline mode must not persist a temporary PLC configuration");
  await page.getByRole("button", { name: "还原", exact: true }).click();
  await page.getByRole("button", { name: "断开", exact: true }).click();
  await page.getByRole("button", { name: "连接", exact: true }).waitFor();
  await page.getByRole("button", { name: "连接", exact: true }).click();
  await page.getByRole("button", { name: "断开", exact: true }).waitFor();
  const config = await read("plc_get_config");
  const version = config.points.find(p => p.tags.includes("protocolVersion"));
  await page.waitForFunction(async id => (await window.__TAURI_INTERNALS__.invoke("plc_get_values"))[id]?.value === 4, version.id);
  const rows = ["已布防", "计划拍照总数"].map(name => page.locator("tr").filter({ has: page.locator(".cell-title").getByText(name, { exact: true }) }));
  for (const row of rows) if (await row.getByRole("button", { name: "写入", exact: true }).isEnabled()) throw new Error("S7 handshake points must not be manually writable");
  await read("plc_write_point", { id: config.points.find(p => p.tags.includes("armed")).id, value: true }).then(() => { throw new Error("Backend accepted a manual handshake write"); }, error => { if (!String(error).includes("禁止手动写入")) throw error; });
  const result = { operation: "离线 S7 下 PLC 草稿还原、拒绝保存临时配置、断开/连接、读回协议版本、握手点禁止手写", passed: true, port: offline.port, protocolVersion: 4 };
  await page.evaluate(result => window.__uiOperations.checks.push(result), result);
  await page.screenshot({ path: "output/playwright/ui-regression/plc-offline-s7.png", fullPage: true });
  return result;
}
