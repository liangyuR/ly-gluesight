import React,{useState} from "react";
import {createRoot} from "react-dom/client";
import {MemoryRouter} from "react-router-dom";
import {ThemeProvider} from "qing-steel";
import "qing-steel/react.css";
import "../../../src/styles.css";
import "../../../src/features/workspace/workspace.css";
import "../../../src/features/workspace/segments.css";
import SegmentWorkbench from "../../../src/features/workspace/SegmentWorkbench";
import OldSegmentWorkbench from "./old-SegmentWorkbench";
import {BenchContext} from "./context";
import workspace from "./workspace.json";
import config from "./benchmark-config.json";
const mode=new URLSearchParams(location.search).get("mode")||"after";
const originals=workspace.teachingPiece.roundId;
const rounds=[originals,config.secondRound];
const doc=workspace.doc;
const groupCount=workspace.captureReview.rounds[originals].groupCount;
(window as any).benchLongTasks=[];
new PerformanceObserver(list=>{for(const entry of list.getEntries())(window as any).benchLongTasks.push({start:entry.startTime,duration:entry.duration});}).observe({entryTypes:["longtask"]});
function App(){
 const [piece,setPiece]=useState<number|null>(null);
 (window as any).benchSwitch=(n:number)=>setPiece(n);
 (window as any).benchState={piece,mode,groupCount,rounds};
 if(piece==null)return <div id="bench-idle">Ready</div>;
 const roundId=rounds[piece];
 const ws={...workspace,teachingPiece:{...workspace.teachingPiece,roundId},captureReview:{rounds:{[roundId]:workspace.captureReview.rounds[originals]}}};
 const plan={segments:doc.segments,cameras:doc.inspect.map(x=>x.camera),segmentDefaults:doc.segmentDefaults,partCalib:doc.partCalib,pieces:[{roundId,groupCount}],progress:{steps:[]}};
 const data={workspace:ws,plan,navigation:null};
 const value={data,doc,busy:false,dirty:false,frameDirty:false,navigationDirty:false,navigationDraft:null,act:async()=>null,setError:()=>{},setNavigationDraft:()=>{}};
 const Workbench=mode==="before"?OldSegmentWorkbench:SegmentWorkbench;
 return <BenchContext.Provider value={value}><div className="wp-page" data-bench-piece={piece} style={{padding:16,maxWidth:1568,margin:"auto"}}><Workbench plan={plan as any} locked="" onDirty={()=>{}}/></div></BenchContext.Provider>;
}
createRoot(document.getElementById("root")!).render(<ThemeProvider defaultTheme="dark" className="app-theme"><MemoryRouter><App/></MemoryRouter></ThemeProvider>);
